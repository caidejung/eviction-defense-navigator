import {test,expect} from '@playwright/test'
test('keyboard entry, validation, local help, court priority and privacy',async({page})=>{
 await page.goto('/')
 await page.keyboard.press('Tab')
 await expect(page.getByText('Skip to content')).toBeFocused()
 await page.keyboard.press('Enter')
 await expect(page.locator('main')).toBeFocused()
 await page.getByText('Find help now →').click()
 await page.getByLabel('City',{exact:true}).selectOption('Berkeley')
 await page.getByLabel('ZIP code').fill('abc')
 await page.getByRole('button',{name:'Continue'}).click()
 await expect(page.getByLabel('ZIP code')).toBeFocused()
 await page.getByLabel('ZIP code').fill('94704')
 await page.getByRole('button',{name:'Continue'}).click()
 await page.getByLabel('Housing problem').selectOption('Unable to pay rent')
 await page.getByRole('button',{name:'Continue'}).click()
 await page.getByLabel('Have you received').selectOption('Upcoming hearing')
 await page.getByRole('button',{name:'Show my resources'}).click()
 await expect(page.locator('article').first()).toContainText('Respond to an eviction lawsuit')
 await expect(page.getByText('Berkeley Housing Retention Program')).toBeVisible()
 await page.getByRole('checkbox').first().check()
 await expect(page.locator('body')).toHaveJSProperty('scrollWidth',await page.evaluate(()=>innerWidth))
 await page.reload()
 await expect(page.getByRole('heading',{name:'Start with your situation.'})).toBeVisible()
})
